suppressMessages(library(ape))
tr <- read.tree("Publication/scripts/analyses/reduced/r1_lg.treefile")
s1 <- read.delim("Publication/scripts/inputs/tsv/S1_genome_metadata.tsv", check.names=FALSE)
cl <- setNames(as.character(s1$clade), s1$tip); sp <- setNames(as.character(s1$species), s1$tip)
key <- sub("\\.fa$","",tr$tip.label)
m <- match(tr$tip.label, s1$tip); if (any(is.na(m))) m[is.na(m)] <- match(key[is.na(m)], s1$tip)
cat("unmatched", sum(is.na(m)), "\n")
print(table(cl[s1$tip[m]]))
og <- tr$tip.label[grepl("Outgroup", cl[s1$tip[m]])]
tr <- root(tr, og, resolve.root=TRUE)
lab <- paste(cl[s1$tip[m]], sp[s1$tip[m]], sep=" | ")
tr2 <- tr; tr2$tip.label <- paste(tr$tip.label, lab)
tr2 <- ladderize(tr2)
write.tree(tr2, "analyses/extended/E_phylo/t1/r1_labeled.nwk")
